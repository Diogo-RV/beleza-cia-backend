-- O script não cria usuários ADMIN nem inclui senhas ou dados pessoais reais.

CREATE TABLE IF NOT EXISTS public.clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(255),
    senha VARCHAR(100) NOT NULL,
    cpf VARCHAR(14) NOT NULL,
    perfil VARCHAR(20) NOT NULL DEFAULT 'CLIENTE',
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_clientes_perfil CHECK (perfil IN ('CLIENTE', 'ADMIN'))
);

-- Compatibilidade com a estrutura antiga do banco, que ainda não tinha email/perfil
-- e podia ter a coluna senha limitada a 30 caracteres.
ALTER TABLE public.clientes ADD COLUMN IF NOT EXISTS email VARCHAR(255);
ALTER TABLE public.clientes ADD COLUMN IF NOT EXISTS perfil VARCHAR(20) DEFAULT 'CLIENTE';
ALTER TABLE public.clientes ALTER COLUMN senha TYPE VARCHAR(100);
ALTER TABLE public.clientes ALTER COLUMN perfil SET DEFAULT 'CLIENTE';
UPDATE public.clientes SET perfil = 'CLIENTE' WHERE perfil IS NULL OR BTRIM(perfil) = '';
ALTER TABLE public.clientes ALTER COLUMN perfil SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_clientes_email_lower
    ON public.clientes (LOWER(email))
    WHERE email IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_clientes_cpf
    ON public.clientes (cpf);

CREATE TABLE IF NOT EXISTS public.servicos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    preco NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    duracao_minutos INTEGER NOT NULL CHECK (duracao_minutos > 0)
);

CREATE TABLE IF NOT EXISTS public.agendamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER,
    servico_id INTEGER NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'confirmado',
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_agendamentos_cliente
        FOREIGN KEY (cliente_id) REFERENCES public.clientes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_agendamentos_servico
        FOREIGN KEY (servico_id) REFERENCES public.servicos(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.bloqueios_agenda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    data_fim TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    motivo VARCHAR(255),
    criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bloqueios_periodo CHECK (data_fim > data_inicio)
);

-- Compatibilidade com bancos antigos que já tinham as tabelas-base.
ALTER TABLE public.agendamentos ADD COLUMN IF NOT EXISTS status VARCHAR(20) DEFAULT 'confirmado';
ALTER TABLE public.agendamentos ADD COLUMN IF NOT EXISTS criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE public.bloqueios_agenda ADD COLUMN IF NOT EXISTS motivo VARCHAR(255);
ALTER TABLE public.bloqueios_agenda ADD COLUMN IF NOT EXISTS criado_em TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP;

CREATE INDEX IF NOT EXISTS ix_agendamentos_data_hora ON public.agendamentos (data_hora);
CREATE INDEX IF NOT EXISTS ix_agendamentos_status_norm_data_hora
    ON public.agendamentos ((LOWER(COALESCE(status, ''))), data_hora DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_agendamentos_cliente_id ON public.agendamentos (cliente_id);
CREATE INDEX IF NOT EXISTS ix_bloqueios_data_inicio_fim ON public.bloqueios_agenda (data_inicio, data_fim);

